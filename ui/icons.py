def svg_data_uri(name: str, color: str = "black", stroke: float = 2) -> str:
    svg = (
        f"<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24' fill='none' stroke='{color}' "
        f"stroke-width='{stroke}' stroke-linecap='round' stroke-linejoin='round'>{_PATHS[name]}</svg>"
    ).replace('"', "'")
    return "data:image/svg+xml," + svg.replace("#", "%23").replace("<", "%3C").replace(">", "%3E")


def icon_css() -> str:
    """Reglas CSS de todos los iconos (se inyectan una vez con el tema)."""
    rules = [
        ".od-ico{display:inline-block;flex:none;vertical-align:-2px;background-color:currentColor;"
        "-webkit-mask:var(--od-i) center/contain no-repeat;mask:var(--od-i) center/contain no-repeat}"
    ]
    rules += [f'.od-i-{name}{{--od-i:url("{svg_data_uri(name)}")}}' for name in _PATHS]
    return "".join(rules)


def icon(name: str, size: int = 16, cls: str = "") -> str:
    if name not in _PATHS:
        raise KeyError(f"Icono desconocido: {name}")
    extra = f" {cls}" if cls else ""
    return (
        f'<span class="od-ico od-i-{name}{extra}" style="width:{size}px;height:{size}px" '
        'aria-hidden="true"></span>'
    )
